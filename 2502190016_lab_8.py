import collections

dirty = [
  "MS-FLG-2026-0041, 24.98",
  "AL-BRK-2026-0007, abc",        # not a number
  "MS-FLG-2026-0043",               # no comma at all
  "SS-GER-2026-0021, 25.04",
  "MS-NEG-2026-0001, -5.00",      # Added impossible value (negative diameter)
  "",                                # empty line
  "ms-shf-2026-0101, 24.88",
]

def parse_line(line):
    line = line.strip()
    if not line:
        raise ValueError("Empty line encountered")

    parts = line.split(', ')

    if len(parts) < 2:
        # Covers lines like "MS-FLG-2026-0043" (missing comma or diameter)
        raise IndexError(f"Malformed line: missing comma or diameter value in '{line}'")

    code_str = parts[0]
    dia_str = parts[1]

    code_parts = code_str.split('-')
    if len(code_parts) < 2:
        # Covers cases like "SOMECODE, 10.0" where the code is missing a family part
        raise ValueError(f"Malformed code: missing family in '{code_str}'")
    family = code_parts[1]

    try:
        dia = float(dia_str)
    except ValueError:
        # Covers lines like "AL-BRK-2026-0007, abc" (non-numeric diameter)
        raise ValueError(f"Invalid diameter value: '{dia_str}'")

    return code_str, family, dia

good, skipped = [], []
for n, line in enumerate(dirty, start=1):
    try:
        code, family, dia = parse_line(line)
        good.append((code, family, dia))
    except ValueError as e:                     # Catch ValueError
        skipped.append((n, "ValueError", str(e), line)) # Store line for reject note
    except IndexError as e:                     # Catch IndexError for malformed lines
        skipped.append((n, "IndexError", str(e), line)) # Store line for reject note

# --- First part of the report ---
print(len(good), "accepted,", len(skipped), "skipped")
for s in skipped:
    print(f"  line {s[0]} → {s[1]}")

# --- Shift Report (computed from good alone) ---
if good:
    total_dia = sum(item[2] for item in good)
    mean_dia = total_dia / len(good)
    count_good = len(good)
    unique_families = sorted(list(set(item[1] for item in good)))

    print("\n--- Shift Report (from good data) ---")
    print(f"Mean Diameter: {mean_dia:.2f}")
    print(f"Accepted Count: {count_good}")
    print(f"Families: {', '.join(unique_families)}")
else:
    print("\nNo good data to generate a shift report.")

# --- Reject Note (line number, alarm name, and raw text of skipped line) ---
print("\n--- Reject Note ---")
for s in skipped:
    # s[0] is line number, s[1] is alarm name, s[3] is the raw text of the skipped line
    print(f"Line {s[0]} ({s[1]}): {s[3]}")

class Shaft:
    def __init__(self, code, diameter):
        if not isinstance(diameter, (int, float)) or diameter <= 0:
            raise ValueError(f"Invalid diameter: {diameter}. Diameter must be a positive number.")
        self.code = code
        self.diameter = diameter

    def __repr__(self):
        return f"Shaft(code='{self.code}', diameter={self.diameter})"

fleet, rejects = [], []
for code, family, dia in good:
    try:
        fleet.append(Shaft(code, dia))       # __init__ may refuse
    except ValueError as e:
        rejects.append((code, str(e)))

print("\n--- Fleet ---")
for s in fleet:
    print(s)

print("\n--- Rejects from Shaft Creation ---")
for r in rejects:
    print(f"Code: {r[0]}, Reason: {r[1]}")

